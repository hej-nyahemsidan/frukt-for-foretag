## Hur vanligt är det med fruktkorgar på svenska kontor?

Fruktkorgar är ett etablerat inslag på många svenska arbetsplatser, särskilt på kontor där arbetsgivaren vill erbjuda ett gemensamt mellanmål i fikarum, kök eller reception. Det finns däremot ingen heltäckande, aktuell svensk statistik som visar exakt hur stor andel av alla företag som har kontorsfrukt. Därför är det bättre att beskriva fruktkorgen som en vanlig personalförmån än att ange en osäker procentsats.

