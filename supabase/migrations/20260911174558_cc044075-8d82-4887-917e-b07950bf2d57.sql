## Vanliga frågor om fruktkorgar på kontoret

### Hur stor fruktkorg behöver ett kontor?

Det beror på antal personer, hur ofta ni får leverans och hur mycket frukt medarbetarna brukar äta. En 4 kg-korg kan vara en bra start för ett mindre kontor. Större arbetsplatser kan välja 6, 9 eller 11 kg eller kombinera flera korgar.

### Hur ofta bör kontorsfrukt levereras?

En leverans i veckan passar många kontor. Om ni är många, har hög konsumtion eller vill sprida ut frukten över veckan kan flera leveransdagar vara bättre.

### Vilken typ av fruktkorg ska vi välja?

Original passar den som vill ha en klassisk blandning. Premium passar när ni vill ha större variation och fler exklusiva frukter efter säsong. Banan passar kontor där bananer går åt snabbt. Ni kan jämföra alternativen i vår [korgväljare på startsidan](/).

### Kan vi ändra storlek senare?

Ja, behovet kan förändras. Följ gärna upp hur mycket som blir kvar och anpassa sedan storlek eller antal korgar.

### Är en fruktkorg tillräcklig för en bra arbetsmiljö?

Nej. Kontorsfrukt kan vara en uppskattad del av arbetsplatsens vardag, men ersätter inte arbetsgivarens bredare ansvar för organisation, belastning, säkerhet och trivsel.

