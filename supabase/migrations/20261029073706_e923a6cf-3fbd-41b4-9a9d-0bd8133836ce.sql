Fruktkorgar till jobbet och fruktlådor kan göra kontorets vardag enklare. Men en bra lösning handlar inte bara om att beställa frukt: mängden behöver passa dem som är på plats, leveransen ska komma rätt dag och frukten behöver stå där den faktiskt blir uppäten. Här är en praktisk checklista för er som ansvarar för kontorets inköp.

Hos Vitaminkorgen räknar vi med **cirka 6–7 kg frukt för 5–12 personer** som utgångspunkt. Vi levererar till företag i Stockholm, Södertälje och Uppsala, och ni väljer själva när ni vill börja. Läs vidare för att planera vardagen, eller gå direkt till [frukt till jobbet](/fruktkorg-pa-jobbet) och [fruktlåda till företag](/fruktlada).

## Fruktkorg eller fruktlåda – börja med hur ni serverar frukten

När ni väljer mellan fruktkorgar och fruktlådor är det bra att först titta på hur frukten ska användas på arbetsplatsen. Ska den stå framme i fikarummet, fördelas mellan flera våningar eller fyllas på i egna skålar? Berätta hur ni vill ha det, så hjälper vi er med upplägget.

En fruktkorg passar som en samlad fruktplats på kontoret. Har ni redan egna skålar och vill fördela frukten mellan flera arbetslag kan ni diskutera ett upplägg med fruktlådor och påfyllning. Fråga oss om leverans och placering för just ert kontor, i stället för att utgå från att alla arbetsplatser behöver samma lösning.

Se [vårt sortiment av fruktkorgar och kontorsprodukter](/produkter) för aktuella alternativ. Våra tre huvudkorgar heter **Original, Premium och Banan**.

## Planera efter när medarbetarna faktiskt är på plats

På ett kontor med hemarbete säger antalet anställda inte alltid hur mycket frukt som behövs. Börja med att räkna dem som brukar vara på kontoret, särskilt under veckans mest välbesökta dagar.

- Vilka dagar är flest på plats?
- Finns det flera fikarum eller arbetslag som behöver frukt?
- Äter ni upp frukten tidigt i veckan eller blir den ofta kvar?
- Kommer besökare eller mötesdeltagare att ta del av frukten?

**Cirka 6–7 kg för 5–12 personer är en riktlinje, inte en garanti för hur länge frukten räcker.** Behovet beror på närvaro, åtgång och hur ofta ni får leverans. Följ upp efter de första leveranserna och prata med kundservice om mängden behöver anpassas. För mer hjälp finns vår [storleksguide för fruktkorgar](/blogg/tips/hur-manga-racker-en-fruktkorg).

## Placera frukten där den blir lätt att ta

En fruktleverans gör mest nytta när frukten är tillgänglig. Välj en tydlig plats i köket, fikarummet eller där kollegorna brukar ta sin paus. Undvik att låta leveransen bli stående i ett förråd där ingen ser den.

Har ni flera våningar kan ni behöva fördela frukten mellan olika platser. Bestäm vem på kontoret som följer upp åtgången, så att ni vet om en våning behöver mer och en annan mindre. Vi kan placera frukt och mjölk där ni önskar enligt ert leveransupplägg.

## Stäm av mängden utan att göra inköpen krångliga

Gör en enkel kontroll mot slutet av veckan: vad har gått åt och vad finns kvar? Om frukten tar slut tidigt kan ni prata med oss om större mängd eller fler leveransdagar. Om mycket ligger kvar bör ni i stället se över mängden och när leveransen kommer.

Det är särskilt användbart inför semesterperioder, konferenser och veckor med färre personer på kontoret. Meddela förändrade behov till kundservice, så kan ni diskutera en lösning som passar perioden. Läs mer om [hur fruktleverans till kontoret fungerar](/blogg/tips/fruktleverans-till-kontoret-sa-fungerar-det).

## Frukt till vardagen, fika och catering till möten

När ett möte eller en utbildningsdag närmar sig kan kontoret behöva mer än frukt. Vitaminkorgen erbjuder även **fika, bullar, tårta, smörgåsar, mackor och frallor**, både som catering och vanliga beställningar. Det går också att beställa mejeri och skivad frukt.

Berätta vad ni behöver, hur många ni blir och vilket datum det gäller. Fråga om aktuellt utbud och eventuella kostönskemål innan beställningen, så att ni kan planera mötesfikat utifrån rätt information. Vi hjälper gärna till med extra beställningar vid sidan av den vanliga fruktleveransen.

## Egen kundportal och personlig kundservice

Våra kunder har en **egen kundportal för sina beställningar**. Behöver ni hjälp med mängd, leverans eller en extra beställning finns personlig kundservice via telefon 010-183 98 36 och e-post info@vitaminkorgen.se.

Tanken är ett långsiktigt samarbete där office managern får hjälp med vardagens inköp, inte bara en leverans som lämnas vid dörren. Ni ska kunna beskriva hur arbetsplatsen fungerar och få hjälp med ett upplägg som passar.

## Kom igång med fruktkorgar till jobbet

Korgarna börjar från **140 kr**. Det är ett frånpris för sortimentet, inte ett fast pris för 6–7 kg. Kontrollera aktuella storlekar och priser i [webshoppen](/produkter) eller be oss ta fram en offert för ert behov.

Er första korg är gratis, ni väljer startdatum och vi levererar direkt när ni önskar börja. Betalningen sker med månadsfaktura.

1. Berätta hur många som brukar vara på plats och vilka dagar ni behöver frukt.
2. Välj korg och diskutera mängd, leveransdagar och placering.
3. Ange önskat startdatum och eventuella extra beställningar av fika.
4. Följ upp åtgången och kontakta oss om behovet förändras.

[Begär en gratis offert](/kontakt) eller [beställ fruktkorgar till jobbet](/bestall). Vill ni läsa mer om lokal leverans hittar ni information på vår sida om [fruktkorg i Stockholm](/fruktkorg-stockholm).
